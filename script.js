// ---------- Timer ----------
function startTimer() {
  clearInterval(state.timerId);
  state.timerId = setInterval(() => {
    state.timeLeft -= 1;
    if (state.timeLeft <= 0) {
      state.timeLeft = 0;
      el.timer.textContent = '0';
      clearInterval(state.timerId);
      endRound(false, "Time's up!");
      return;
    }
    el.timer.textContent = state.timeLeft;
    el.timer.classList.toggle('low', state.timeLeft <= 10);
  }, 1000);
}

// Any active pause source (manual button or tutorial) freezes the clock
// and hides the board so a pause can't be used to stall for free think time.
function applyPauseState() {
  const anyPaused = state.paused.manual || state.paused.tutorial;
  if (anyPaused) {
    clearInterval(state.timerId);
    state.timerId = null;
    el.timer.classList.add('paused');
    el.board.classList.add('board-hidden');
  } else {
    el.timer.classList.remove('paused');
    el.board.classList.remove('board-hidden');
    if (!state.ended && !state.timerId && !isUntimed()) {
      startTimer();
    }
  }
}

// ---------- Sharing ----------
function buildShareText(won) {
  const { start, target, par } = state.puzzle;
  const lines = [];
  lines.push(state.mode === 'daily'
    ? `Word Ladder Duel #${dayNumberFor(state.dailyDate)} (${state.dailyTier}-letter) 🪜`
    : 'Word Ladder Duel 🪜');
  lines.push(`${start.toUpperCase()} -> ${target.toUpperCase()}`);
  lines.push(won
    ? (isUntimed()
      ? `Solved in ${state.moves}/${par} moves`
      : `Solved in ${state.moves}/${par} moves - ${state.timeLeft}s left`)
    : `Didn't finish (par ${par})`);
  for (let i = 1; i < state.path.length; i++) {
    const prev = state.path[i - 1], cur = state.path[i];
    let row = '';
    for (let j = 0; j < cur.length; j++) row += (cur[j] === prev[j]) ? '⬜' : '🟩';
    lines.push(row);
  }
  return lines.join('\n');
}

// ---------- Duel challenges ----------
// Encodes the just-finished puzzle + the sender's result into a URL so a
// friend opening it plays the exact same start/target and sees how they
// compared - no server needed, the whole challenge lives in the link.
function encodeDuelPayload(payload) {
  return encodeURIComponent(btoa(JSON.stringify(payload)));
}
function decodeDuelPayload(str) {
  try { return JSON.parse(atob(decodeURIComponent(str))); } catch (e) { return null; }
}

function buildDuelLink() {
  const payload = {
    s: state.puzzle.start,
    t: state.puzzle.target,
    l: state.puzzle.len,
    md: isUntimed() ? 'relaxed' : 'random',
    mv: state.moves,
    tl: isUntimed() ? null : state.timeLeft,
    won: state.path[state.path.length - 1] === state.puzzle.target,
  };
  const url = new URL(location.href);
  url.search = '';
  url.searchParams.set('duel', encodeDuelPayload(payload));
  return url.toString();
}

async function copyTextToClipboard(text) {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch (e) {
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.style.position = 'fixed';
    ta.style.opacity = '0';
    document.body.appendChild(ta);
    ta.select();
    let copied = false;
    try { document.execCommand('copy'); copied = true; } catch (e2) { /* ignore */ }
    document.body.removeChild(ta);
    return copied;
  }
}

