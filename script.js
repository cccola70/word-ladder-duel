function formatLobbyCountdown(remainingMs) {
  const totalSec = Math.max(0, Math.ceil(remainingMs / 1000));
  const m = Math.floor(totalSec / 60);
  const s = totalSec % 60;
  el.lobbyCountdown.textContent = `${m}:${String(s).padStart(2, '0')}`;
  el.lobbyCountdown.classList.toggle('urgent', totalSec <= 3);
}

function leaveLobby() {
  clearInterval(state.groupLobbyTimerId);
  state.groupLobbyTimerId = null;
  el.lobbyOverlay.classList.remove('visible');
}

// Opens a group duel link: plays immediately if the start time has already
// passed (a late joiner), otherwise shows the synced waiting lobby and
// starts the round the instant every open tab's clock reaches startAt.
function openGroupLink(payload) {
  // Whatever overlay was showing before (a win/lose screen, the setup form)
  // shares the same stacking layer as the lobby and would otherwise paint
  // on top of it, since it comes later in the document.
  el.overlay.classList.remove('visible');
  el.groupSetupOverlay.classList.remove('visible');
  el.pauseOverlay.classList.remove('visible');

  if (payload.results.length >= GROUP_DUEL_MAX_PLAYERS) {
    el.lobbyInfo.textContent = `${payload.l}-Letter · ${payload.md === 'relaxed' ? 'Relaxed' : 'Timed'}`;
    el.lobbyCountdown.hidden = true;
    el.lobbyHint.textContent = `This duel already has its ${GROUP_DUEL_MAX_PLAYERS} players. Here's how they did:`;
    renderGroupLeaderboard(el.lobbyLeaderboard, payload.results);
    el.lobbyLeaveBtn.textContent = 'Start Your Own Puzzle';
    el.lobbyOverlay.classList.add('visible');
    return;
  }

  el.lobbyCountdown.hidden = false;
  el.lobbyLeaderboard.hidden = true;
  el.lobbyLeaveBtn.textContent = 'Leave Lobby';

  if (Date.now() >= payload.startAt) {
    newPuzzle('group', { groupPayload: payload });
    return;
  }

  // Suspend whatever round was already in progress (if any) so its timer
  // can't keep ticking - and potentially end the round - while hidden
  // behind the lobby overlay during a long wait.
  clearInterval(state.timerId);
  state.timerId = null;
  el.board.classList.add('board-hidden');

  el.lobbyInfo.textContent = `${payload.l}-Letter · ${payload.md === 'relaxed' ? 'Relaxed' : 'Timed'}`;
  el.lobbyHint.textContent = "Waiting for the start time — get everyone's link open before then.";
  el.lobbyOverlay.classList.add('visible');
  formatLobbyCountdown(payload.startAt - Date.now());

  clearInterval(state.groupLobbyTimerId);
  state.groupLobbyTimerId = setInterval(() => {
    const remaining = payload.startAt - Date.now();
    if (remaining <= 0) {
      leaveLobby();
      newPuzzle('group', { groupPayload: payload });
      return;
    }
    formatLobbyCountdown(remaining);
  }, 200);
}

// ---------- Puzzle lifecycle ----------
function newPuzzle(mode, opts) {
  mode = mode || 'random';
  state.mode = mode;
  if (mode !== 'duel') state.duelOpponent = null;
  if (mode !== 'daily') state.dailyTier = null;
  if (mode !== 'group') state.groupPayload = null;
  leaveLobby();
  el.board.classList.remove('board-hidden');
  hideShareButton();
  hideChallengeButton();
  el.duelResult.hidden = true;
  el.duelResult.className = 'duel-result';
  el.groupResult.hidden = true;
  state.paused.manual = false;
  el.pauseOverlay.classList.remove('visible');

  // Hide whichever mode button matches the mode already in play - picking
  // it again would just be confusing - while leaving the other switches
  // visible so there's always a way to change mode.
  el.newBtn.hidden = mode === 'random';
  el.relaxedBtn.hidden = mode === 'relaxed';
  for (const len of DAILY_TIERS) {
    el.dailyTierBtns[len].hidden = false;
  }

  if (mode === 'daily') {
    const tier = (opts && opts.tier) || state.dailyTier || 5;
    el.dailyTierBtns[tier].hidden = true;
    const dateStr = todayDateStr();
    state.dailyDate = dateStr;
    state.dailyTier = tier;
    const rand = mulberry32(seedFromString(`word-ladder-${dateStr}-${tier}`));
    state.puzzle = pickPuzzle(rand, tier);
    el.modeBadge.textContent = `Daily Puzzle #${dayNumberFor(dateStr)} · ${tier}-Letter`;
    el.modeBadge.classList.remove('relaxed', 'duel', 'group');
    el.modeBadge.classList.add('daily');

    const existing = loadDailyRecord(dateStr, tier);
    if (existing) {
      state.path = existing.path || [state.puzzle.start];
      state.moves = existing.moves || 0;
      state.timeLeft = existing.timeLeft || 0;
      state.ended = true;
      state.targetDist = bfsDistances(state.puzzle.graph, state.puzzle.target);
      clearInterval(state.timerId);
      el.timer.classList.remove('low');
      el.timer.textContent = state.timeLeft;
      renderTiles(el.goalTiles, state.puzzle.target);
      renderLadder();
      renderInputTiles('', state.puzzle.len);
      el.wordInput.value = '';
      el.wordInput.maxLength = state.puzzle.len;
      setMessage("You already played today's puzzle at this length. Come back tomorrow for a new one!");
      updateStats();
      el.overlayTitle.textContent = existing.overlayTitle;
      el.overlayText.textContent = existing.overlayText;
      showShareButton(existing.shareText);
      el.overlay.classList.add('visible');
      refreshDailyTierButtons();
      return;
    }
  } else if (mode === 'duel') {
    const payload = opts && opts.duelPayload;
    const graph = payload && GRAPHS[payload.l];
    const dist = graph && graph.has(payload.s) ? bfsDistances(graph, payload.s) : null;
    const par = dist && dist.get(payload.t);
    if (!payload || !graph || !graph.has(payload.s) || !graph.has(payload.t) || par === undefined) {
      // Bad or stale link - fall back to a normal random puzzle instead of a dead page.
      newPuzzle('random');
      return;
    }
    state.dailyDate = null;
    state.duelOpponent = payload;
    state.puzzle = { start: payload.s, target: payload.t, par, len: payload.l, graph };
    el.modeBadge.textContent = 'Duel Challenge';
    el.modeBadge.classList.remove('daily', 'relaxed', 'group');
    el.modeBadge.classList.add('duel');
  } else if (mode === 'group') {
    const payload = opts && opts.groupPayload;
    const graph = payload && GRAPHS[payload.l];
    const dist = graph && graph.has(payload.s) ? bfsDistances(graph, payload.s) : null;
    const par = dist && dist.get(payload.t);
    if (!payload || !graph || !graph.has(payload.s) || !graph.has(payload.t) || par === undefined) {
      // Bad or stale link - fall back to a normal random puzzle instead of a dead page.
      newPuzzle('random');
      return;
    }
    state.dailyDate = null;
    state.groupPayload = payload;
    state.puzzle = { start: payload.s, target: payload.t, par, len: payload.l, graph };
    el.modeBadge.textContent = `Group Duel · ${payload.l}-Letter · ${payload.md === 'relaxed' ? 'Relaxed' : 'Timed'}`;
    el.modeBadge.classList.remove('daily', 'relaxed', 'duel');
    el.modeBadge.classList.add('group');
  } else {
    state.dailyDate = null;
    state.puzzle = pickPuzzle();
    el.modeBadge.classList.remove('daily', 'relaxed', 'duel', 'group');
    if (mode === 'relaxed') {
      el.modeBadge.textContent = 'Relaxed Mode';
      el.modeBadge.classList.add('relaxed');
    } else {
      el.modeBadge.textContent = 'Random Puzzle';
    }
  }

  state.path = [state.puzzle.start];
  state.moves = 0;
  state.timeLeft = 60;
  state.ended = false;
  state.targetDist = bfsDistances(state.puzzle.graph, state.puzzle.target);
  clearInterval(state.timerId);
  state.timerId = null;
  el.timer.classList.remove('low', 'paused', 'infinite');
  const untimed = isUntimed();
  if (untimed) {
    el.timer.textContent = '∞';
    el.timer.classList.add('infinite');
  } else {
    el.timer.textContent = state.timeLeft;
  }
  renderTiles(el.goalTiles, state.puzzle.target);
  renderLadder();
  renderInputTiles('', state.puzzle.len);
  setMessage(untimed
    ? 'No clock this round — change one letter at a time, whenever you like.'
    : 'Change one letter at a time to reach the goal word.');
  el.wordInput.value = '';
  el.wordInput.maxLength = state.puzzle.len;
  el.wordInput.focus();
  updateStats();
  el.overlay.classList.remove('visible');
  if (!untimed) {
    startTimer();
  }
}

function endRound(won, reasonText) {
  if (state.ended) return;
  state.ended = true;
  clearInterval(state.timerId);
  const untimed = isUntimed();
  let finalScore = 0;
  if (won) {
    const extra = state.moves - state.puzzle.par;
    const penalty = Math.max(0, extra) * 40;
    const timeBonus = untimed ? 0 : state.timeLeft * 2;
    const roundScore = Math.max(60, 500 - penalty + timeBonus);
    finalScore = roundScore;
    state.score += roundScore;
    state.streak += 1;
    if (state.score > state.best) {
      state.best = state.score;
      localStorage.setItem('wld_best', String(state.best));
    }
    el.overlayTitle.textContent = 'Solved!';
    el.overlayText.textContent = untimed
      ? `${state.puzzle.start.toUpperCase()} -> ${state.puzzle.target.toUpperCase()} in ${state.moves} moves (par ${state.puzzle.par}). +${roundScore} points.`
      : `${state.puzzle.start.toUpperCase()} -> ${state.puzzle.target.toUpperCase()} in ${state.moves} moves (par ${state.puzzle.par}). +${roundScore} points, ${state.timeLeft}s left.`;
    playSound('win');
    launchConfetti();
  } else {
    state.streak = 0;
    const path = reconstructPath(currentWord());
    el.overlayTitle.textContent = reasonText || 'Round over';
    el.overlayText.textContent = path
      ? `One valid path: ${path.join(' -> ').toUpperCase()}`
      : `The goal word was ${state.puzzle.target.toUpperCase()}.`;
    playSound('lose');
  }
  updateStats();
  el.overlay.classList.add('visible');

  const shareText = buildShareText(won);
  showShareButton(shareText);
  if (state.mode !== 'daily') {
    showChallengeButton();
  }

  if (state.mode === 'duel' && state.duelOpponent) {
    showDuelResult(won);
  }

  if (state.mode === 'group' && state.groupPayload) {
    showGroupResult(won);
  }

  if (state.mode === 'daily') {
    updateDailyStreak(state.dailyDate, won);
    saveDailyRecord(state.dailyDate, state.dailyTier, {
      won,
      moves: state.moves,
      timeLeft: state.timeLeft,
      finalScore,
      path: state.path,
      overlayTitle: el.overlayTitle.textContent,
      overlayText: el.overlayText.textContent,
      shareText,
    });
    refreshDailyTierButtons();
  }
}

// Compares this attempt against the opponent's result baked into the duel
// link, and shows a verdict: fewer moves wins; a moves tie is broken by
// time left (when the round was timed); otherwise it's a tie.
function showDuelResult(won) {
  const opp = state.duelOpponent;
  const oppTimed = opp.md !== 'relaxed';
  const oppSummary = !won
    ? (opp.won ? `Your friend solved it in ${opp.mv} moves${oppTimed ? `, ${opp.tl}s left` : ''}.` : "Your friend didn't finish it either.")
    : null;

  let verdict, cls;
  if (!won) {
    verdict = opp.won ? 'Your friend won this round.' : "It's a tie — neither of you finished.";
    cls = opp.won ? 'lose' : 'tie';
  } else if (!opp.won) {
    verdict = 'You beat your friend! 🏆';
    cls = 'win';
  } else if (state.moves < opp.mv) {
    verdict = 'You beat your friend! 🏆';
    cls = 'win';
  } else if (state.moves > opp.mv) {
    verdict = 'Your friend won this round.';
    cls = 'lose';
  } else if (!isUntimed() && oppTimed && state.timeLeft !== opp.tl) {
    verdict = state.timeLeft > opp.tl ? 'You beat your friend! 🏆' : 'Your friend won this round.';
    cls = state.timeLeft > opp.tl ? 'win' : 'lose';
  } else {
    verdict = "It's a tie!";
    cls = 'tie';
  }

  const friendLine = won
    ? `Friend: ${opp.mv} moves${oppTimed && opp.won ? `, ${opp.tl}s left` : ''}${!opp.won ? " (didn't finish)" : ''}`
    : oppSummary;

  el.duelResult.textContent = `${friendLine}\n${verdict}`;
  el.duelResult.className = `duel-result ${cls}`;
  el.duelResult.hidden = false;
}

function reconstructPath(fromWord, avoidUsed = true) {
  // BFS from fromWord to target using the puzzle graph, return word sequence.
  // By default avoids routing back through words already used earlier in
  // this attempt, so the shown solution doesn't double back on the
  // player's own history; falls back to an unrestricted search if no such
  // route exists, so a solution is still shown whenever one is possible.
  const { graph, target } = state.puzzle;
  if (!graph.has(fromWord)) return null;
  const prev = new Map([[fromWord, null]]);
  const queue = [fromWord];
  let head = 0;
  while (head < queue.length) {
    const cur = queue[head++];
    if (cur === target) break;
    for (const nb of graph.get(cur)) {
      if (prev.has(nb) || (avoidUsed && state.path.includes(nb) && nb !== fromWord)) continue;
      prev.set(nb, cur);
      queue.push(nb);
    }
  }
  if (!prev.has(target)) {
    return avoidUsed ? reconstructPath(fromWord, false) : null;
  }
  const seq = [];
  let node = target;
  while (node !== null) {
    seq.unshift(node);
    node = prev.get(node);
  }
  return seq;
}

